// Tiny helpers for building the page without a framework.

type Child = Node | string | null | undefined | false;

export function h<K extends keyof HTMLElementTagNameMap>(
  tag: K,
  props: Partial<Record<string, unknown>> = {},
  ...children: Child[]
): HTMLElementTagNameMap[K] {
  const el = document.createElement(tag);
  for (const [key, value] of Object.entries(props)) {
    if (value === undefined || value === null || value === false) continue;
    if (key.startsWith("on") && typeof value === "function") {
      el.addEventListener(key.slice(2).toLowerCase(), value as EventListener);
    } else if (key === "class") {
      el.className = String(value);
    } else if (key === "style" && typeof value === "object") {
      // setProperty also handles CSS variables like "--island".
      for (const [prop, v] of Object.entries(value as Record<string, string>)) el.style.setProperty(prop, v);
    } else if (key === "html") {
      el.innerHTML = String(value);
    } else {
      el.setAttribute(key, value === true ? "" : String(value));
    }
  }
  for (const child of children) {
    if (child === null || child === undefined || child === false) continue;
    el.append(child);
  }
  return el;
}

/** Trusted SVG markup (generated by our own code) as an element. */
export function svg(markup: string, className = "visual"): HTMLElement {
  return h("div", { class: className, html: markup });
}

function escapeHtml(text: string): string {
  return text.replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[c]!);
}

/** Text with **bold** parts, safely escaped. */
export function rich(text: string, tag: "p" | "span" | "div" = "p", className?: string): HTMLElement {
  const html = escapeHtml(text).replace(/\*\*(.+?)\*\*/g, "<strong>$1</strong>");
  return h(tag, { class: className, html });
}

export function starsText(n: number, max = 3): string {
  return "★".repeat(n) + "☆".repeat(Math.max(0, max - n));
}
